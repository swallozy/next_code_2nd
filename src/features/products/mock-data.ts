export const STORE_MOCK_PRODUCTS: StoreProduct[] = MOCK_PRODUCTS.map((item) => {
  const cat = (item.categoryId || '').toLowerCase()
  const parent = (item.parentCategoryId || '').toLowerCase()
  let normCategory: 'housing' | 'keyboards' | 'switches' | 'keycaps' = 'keyboards'
  if (parent.includes('hous')) normCategory = 'housing'
  else if (parent.includes('switch')) normCategory = 'switches'
  else if (parent.includes('keycap')) normCategory = 'keycaps'

  const gallery =
    item.galleryImages && item.galleryImages.length > 0 ? item.galleryImages : [item.thumbnailUrl]
  const images: StoreMedia[] = gallery.map((url: string, idx: number) => ({
    id: `${item.productId}-${idx}`,
    url,
    alt: item.name,
  }))

  const isSoldOut = Boolean(item.isSoldOut) || item.stockQuantity <= 0 || item.status === 'SOLD_OUT'

  return {
    id: String(item.productId),
    slug: String(item.productId),
    name: item.name,
    brand: 'MONO / STUDIO',
    category: normCategory,
    categoryId: item.categoryId,
    parentCategoryId: item.parentCategoryId,
    subCategoryName: item.subCategoryName,
    basePrice: item.basePrice,
    stockQuantity: item.stockQuantity,
    shippingFee: 0,
    isSoldOut,
    status: isSoldOut ? 'SOLD_OUT' : 'ACTIVE',
    description: item.description,
    layout: item.layout,
    switchType: item.switchType,
    material: item.material,
    style: item.style,
    images,
    options: [],
  }
})
